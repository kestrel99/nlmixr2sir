# S1/S2: weight degeneracy diagnostics, and a noise band from the real resampler
#
# Normalising the importance weights on the log scale stops them overflowing.
# It says nothing about whether they are informative: a run in which one
# candidate carries almost all the weight normalises perfectly well and reports
# nothing unusual, while the retained sample is effectively a handful of points.
# These are the numbers that expose that.

test_that("weight diagnostics are exact for uniform weights", {
  # n equal weights: ESS is n, perplexity is n, the largest weight is 1/n.
  p <- rep(1 / 8, 8L)
  d <- .sirWeightDiagnostics(p, nSuccessful = 8L)
  expect_equal(d$ess, 8, tolerance = 1e-12)
  expect_equal(d$essFraction, 1, tolerance = 1e-12)
  expect_equal(d$maxWeight, 1 / 8, tolerance = 1e-12)
  expect_equal(d$perplexity, 8, tolerance = 1e-12)
})

test_that("weight diagnostics are exact for a fully degenerate weight", {
  # All the mass on one candidate: ESS and perplexity are both 1.
  p <- c(1, rep(0, 9L))
  d <- .sirWeightDiagnostics(p, nSuccessful = 10L)
  expect_equal(d$ess, 1, tolerance = 1e-12)
  expect_equal(d$essFraction, 0.1, tolerance = 1e-12)
  expect_equal(d$maxWeight, 1, tolerance = 1e-12)
  expect_equal(d$perplexity, 1, tolerance = 1e-12)
})

test_that("ESS falls between the degenerate and uniform extremes", {
  p <- c(0.7, 0.2, 0.05, 0.05)
  d <- .sirWeightDiagnostics(p, nSuccessful = 4L)
  expect_gt(d$ess, 1)
  expect_lt(d$ess, 4)
  # 1 / sum(p^2), computed by hand.
  expect_equal(d$ess, 1 / (0.7^2 + 0.2^2 + 2 * 0.05^2), tolerance = 1e-12)
  # Perplexity is exp of the Shannon entropy of the weights.
  ent <- -sum(p * log(p))
  expect_equal(d$perplexity, exp(ent), tolerance = 1e-12)
})

test_that("weight diagnostics ignore zero-probability candidates", {
  # Failed evaluations carry probability zero and must not count as support.
  p <- c(rep(1 / 4, 4L), rep(0, 6L))
  d <- .sirWeightDiagnostics(p, nSuccessful = 4L)
  expect_equal(d$ess, 4, tolerance = 1e-12)
  expect_equal(d$nNonNegligible, 4L)
})

test_that("the iteration summary carries the weight diagnostics", {
  skip_on_cran()
  s <- iter1()$iterSummary
  for (nm in c("ess", "essFraction", "maxWeight", "perplexity", "nNonNegligible")) {
    expect_true(nm %in% names(s), info = nm)
  }
  expect_gt(s$ess, 0)
  expect_lte(s$ess, s$nSuccessful)
  expect_gte(s$essFraction, 0)
  expect_lte(s$essFraction, 1)
})

test_that("a degenerate importance sample warns", {
  skip_on_cran()
  fit <- theoFit()
  # A proposal far narrower than the likelihood makes a handful of candidates
  # carry the weight, which is exactly the situation the diagnostics exist to
  # surface.
  expect_warning(
    suppressMessages(sirRunIteration(
      fit,
      mu = .sirProposalMu(fit),
      proposalCov = sirGetProposalCov(fit) * 400,
      nSamples = 30L,
      nResample = 6L,
      iterNum = 1L,
      recenter = FALSE,
      boxcox = FALSE,
      directory = NULL
    )),
    "effective sample size|weight"
  )
})

