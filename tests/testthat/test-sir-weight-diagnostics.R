test_that("the noise band uses the run's own resampler and cap", {
  skip_on_cran()
  obj <- sirObj()
  quant <- seq(0.1, 0.9, by = 0.1)

  # The band must be reproducible given a seed, because it is generated by the
  # same weighted resampler that produced the retained sample.
  set.seed(101)
  a <- .sirDofvNoise(obj, 1L, quant, nReplicate = 50L, capResampling = 1)
  set.seed(101)
  b <- .sirDofvNoise(obj, 1L, quant, nReplicate = 50L, capResampling = 1)
  expect_equal(a, b)

  expect_true(all(a$low <= a$high))
  expect_equal(nrow(a), length(quant))
})

test_that("noise replicates obey the resampling cap", {
  skip_on_cran()
  # The property that distinguishes the real resampler from the sample.int()
  # call this used to use: with limited replacement no candidate may appear
  # more than `cap` times, whereas unlimited replacement lets one candidate
  # take every slot. Checked on sirResample() directly, because that is now
  # what generates the band.
  set.seed(303)
  n <- 6L
  probs <- c(0.5, 0.2, 0.12, 0.1, 0.05, 0.03)
  mat <- matrix(seq_len(n), ncol = 1L, dimnames = list(NULL, "deltaofv"))
  w <- data.frame(prob_resample = probs)

  for (cap in c(1L, 2L, 3L)) {
    drawn <- sirResample(mat, w, m = min(10L, n * cap), capResampling = cap)
    expect_lte(max(table(drawn$selectionOrder)), cap)
  }
})

test_that("the noise band honours capResampling rather than assuming 1", {
  skip_on_cran()
  obj <- sirObj()
  quant <- seq(0.1, 0.9, by = 0.1)

  set.seed(202)
  cap1 <- .sirDofvNoise(obj, 1L, quant, nReplicate = 80L, capResampling = 1)
  set.seed(202)
  cap3 <- .sirDofvNoise(obj, 1L, quant, nReplicate = 80L, capResampling = 3)

  # Limited replacement lets one candidate appear up to `cap` times, which is a
  # different resampler and so a different band. If the cap were ignored these
  # would be identical.
  expect_false(isTRUE(all.equal(cap1$low, cap3$low)))
})

test_that("the convergence plot passes the run's controls to the noise band", {
  skip_on_cran()
  obj <- sirObj()
  # The effective controls are recorded on the result so diagnostics describe
  # the algorithm that actually produced the retained sample.
  expect_false(is.null(attr(obj, "control")))
  expect_no_error(suppressWarnings(plot(obj, type = "convergence", noise = TRUE)))
})
